-- Run with a role authorized to create these demo resources.
CREATE WAREHOUSE IF NOT EXISTS DATAFLOW_DEMO_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS DATAFLOW_DEMO;
CREATE SCHEMA IF NOT EXISTS DATAFLOW_DEMO.ANALYTICS;
USE WAREHOUSE DATAFLOW_DEMO_WH;
USE SCHEMA DATAFLOW_DEMO.ANALYTICS;
CREATE FILE FORMAT IF NOT EXISTS DATAFLOW_CSV TYPE = CSV SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE;
CREATE STAGE IF NOT EXISTS INCOMING FILE_FORMAT = DATAFLOW_CSV;
CREATE TABLE IF NOT EXISTS MONTHLY_REVENUE (
 MONTH DATE, NET_REVENUE_CENTS NUMBER(20,0), MOM_PCT NUMBER(12,2),
 YOY_PCT NUMBER(12,2), ROLLING_3_MONTH_REVENUE_CENTS NUMBER(20,0)
);
-- From SnowSQL: PUT file:///absolute/path/to/Revenue.csv @INCOMING OVERWRITE=TRUE;
COPY INTO MONTHLY_REVENUE FROM @INCOMING FILES = ('Revenue.csv.gz') ON_ERROR = 'ABORT_STATEMENT';
CREATE OR REPLACE VIEW V_MONTHLY_REVENUE AS
SELECT MONTH, NET_REVENUE_CENTS / 100.00 AS NET_REVENUE_USD,
       MOM_PCT, YOY_PCT, ROLLING_3_MONTH_REVENUE_CENTS / 100.00 AS ROLLING_3_MONTH_USD
FROM MONTHLY_REVENUE;
